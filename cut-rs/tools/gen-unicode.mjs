// Writes crates/cut-app/src/ai/unicode.rs: the Unicode classes the text AI's line breaking tests with regular
// expressions in ai.js and speech.js (\p{Script=Hangul}, Han, Hiragana, Katakana, the closing punctuation
// \p{Pe}\p{Pf}\p{Po}), as code point ranges taken from this Node's own regular expressions, so both sides agree.
//   node tools/gen-unicode.mjs && rustfmt crates/cut-app/src/ai/unicode.rs
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(HERE, '..', 'crates', 'cut-app', 'src', 'ai', 'unicode.rs');

const CLASSES = [
  ['HANGUL', /\p{Script=Hangul}/u, 'Hangul (`\\p{Script=Hangul}`): Korean text.'],
  ['CJK', /[\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}]/u, 'Han, Hiragana and Katakana: Japanese and Chinese text.'],
  ['CLOSING', /^[\p{Pe}\p{Pf}\p{Po}]$/u, 'Closing, final and other punctuation (`\\p{Pe}\\p{Pf}\\p{Po}`).'],
];

function ranges(re) {
  const out = [];
  let start = -1;
  for (let cp = 0; cp <= 0x110000; cp++) {
    const hit = cp < 0x110000 && !(cp >= 0xd800 && cp <= 0xdfff) && re.test(String.fromCodePoint(cp));
    if (hit && start < 0) start = cp;
    if (!hit && start >= 0) { out.push([start, cp - 1]); start = -1; }
  }
  return out;
}

const hex = (n) => `0x${n.toString(16).toUpperCase().padStart(4, '0')}`;
let text = `//! Unicode classes of the text AI's line breaking, generated by \`tools/gen-unicode.mjs\` from Node ${process.version}'s
//! regular expressions (do not edit; run the script again).\n`;
for (const [name, re, doc] of CLASSES) {
  const list = ranges(re);
  text += `\n/// ${doc}\npub const ${name}: &[(u32, u32)] = &[\n`;
  for (let i = 0; i < list.length; i += 6) {
    text += `    ${list.slice(i, i + 6).map(([a, b]) => `(${hex(a)}, ${hex(b)})`).join(', ')},\n`;
  }
  text += '];\n';
}
text += `
/// Whether \`c\` is in one of the sorted ranges.
pub fn within(c: char, table: &[(u32, u32)]) -> bool {
    let c = c as u32;
    table.binary_search_by(|&(a, b)| if b < c { std::cmp::Ordering::Less } else if a > c { std::cmp::Ordering::Greater } else { std::cmp::Ordering::Equal }).is_ok()
}
`;
writeFileSync(OUT, text);
console.log(`wrote ${OUT}`);
