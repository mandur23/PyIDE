// Builds renderer/core/icons.js from PyCharm's New UI (expui) SVG icons extracted with REA.
// Usage: node tools/build-icons.mjs <platform-ide.jar extract dir> <terminal.jar extract dir> <python.community.impl.jar extract dir>
// The icons come from the IntelliJ Platform (Apache License 2.0, https://github.com/JetBrains/intellij-community).
import { readFileSync, writeFileSync } from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const [platform, terminal, python] = process.argv.slice(2);
if (!python) throw new Error('usage: node tools/build-icons.mjs <platform> <terminal> <python>');

const SOURCES = {
  project: [platform, 'expui/toolwindows/project.svg'],
  commit: [platform, 'expui/toolwindows/commit.svg'],
  structure: [platform, 'expui/toolwindows/structure.svg'],
  services: [platform, 'expui/toolwindows/services.svg'],
  run: [platform, 'expui/toolwindows/run.svg'],
  debug: [platform, 'expui/toolwindows/debug.svg'],
  find: [platform, 'expui/toolwindows/find.svg'],
  problems: [platform, 'expui/toolwindows/problems.svg'],
  todo: [platform, 'expui/toolwindows/todo.svg'],
  vcs: [platform, 'expui/toolwindows/vcs.svg'],
  bookmarks: [platform, 'expui/toolwindows/bookmarks.svg'],
  notifications: [platform, 'expui/toolwindows/notifications.svg'],
  more: [platform, 'expui/toolwindows/toolWindowOverflow.svg'],
  pin: [platform, 'expui/general/pin.svg'],
  pinSelected: [platform, 'expui/general/pinSelected.svg'],
  terminal: [terminal, 'icons/expui/toolwindow/terminal.svg'],
  pythonConsole: [python, 'icons/com/jetbrains/pythonCore/python/expui/pythonConsoleToolWindow.svg'],
  pythonPackages: [python, 'icons/com/jetbrains/pythonCore/python/expui/pythonPackages.svg'],
};

// The light variants draw in Gray7 (#6C707E); that gray becomes currentColor so CSS sets the color per theme and state.
const GRAYS = /#6C707E|#818594|#6C707E/gi;
const icons = {};
for (const [name, [dir, rel]] of Object.entries(SOURCES)) {
  let svg = readFileSync(path.join(dir, ...rel.split('/')), 'utf8')
    .replace(/<\?xml[^>]*>\s*/, '')
    .replace(/<!--[\s\S]*?-->\s*/g, '')
    .replace(GRAYS, 'currentColor')
    .replace(/\s+/g, ' ')
    .trim();
  svg = svg.replace('<svg ', '<svg aria-hidden="true" ');
  icons[name] = svg;
}

const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'renderer', 'core', 'icons.js');
writeFileSync(out, `// Generated by tools/build-icons.mjs from PyCharm's New UI icons (IntelliJ Platform, Apache License 2.0). Do not edit.
window.PYIDE_ICONS = ${JSON.stringify(icons, null, 2)};
`);
console.log(`wrote ${Object.keys(icons).length} icons to ${out}`);
