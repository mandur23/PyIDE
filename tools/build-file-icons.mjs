// Builds renderer/core/file-icons-data.js: the file type icons of PyCharm's New UI (light and dark variants), plus the
// few PyCharm has no file type icon for (video, audio, PDF) drawn in the same style in tools/file-icons/.
// Usage: node tools/build-file-icons.mjs <intellij.platform.ide.jar dir> <intellij.python.parser.jar dir>
// (each the folder the jar was extracted to). The icons come from the IntelliJ Platform (Apache License 2.0).
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const [platform, pythonParser] = process.argv.slice(2);
if (!pythonParser) throw new Error('usage: node tools/build-file-icons.mjs <platform jar dir> <python parser jar dir>');
const here = path.dirname(fileURLToPath(import.meta.url));

const clean = (svg) => svg
  .replace(/<\?xml[^>]*>\s*/, '')
  .replace(/<!--[\s\S]*?-->\s*/g, '')
  .replace(/\s+/g, ' ')
  .trim()
  .replace('<svg ', '<svg aria-hidden="true" ');

const light = {};
const dark = {};
// name -> [folder, file stem]
const sources = {};
const typesDir = path.join(platform, 'expui', 'fileTypes');
for (const f of readdirSync(typesDir)) {
  const m = /^([A-Za-z]+)\.svg$/.exec(f);
  if (m) sources[m[1]] = [typesDir, m[1]];
}
sources.folder = [path.join(platform, 'expui', 'nodes'), 'folder'];
sources.package = [path.join(platform, 'expui', 'nodes'), 'package'];
sources.python = [path.join(pythonParser, 'icons', 'com', 'jetbrains', 'python', 'parser', 'expui'), 'python'];
const custom = path.join(here, 'file-icons');
for (const f of readdirSync(custom)) {
  const m = /^([A-Za-z]+)\.svg$/.exec(f);
  if (m) sources[m[1]] = [custom, m[1]];
}

for (const [name, [dir, stem]] of Object.entries(sources).sort(([a], [b]) => a.localeCompare(b))) {
  light[name] = clean(readFileSync(path.join(dir, `${stem}.svg`), 'utf8'));
  const d = path.join(dir, `${stem}_dark.svg`);
  if (existsSync(d)) dark[name] = clean(readFileSync(d, 'utf8'));
}

const out = path.join(here, '..', 'renderer', 'core', 'file-icons-data.js');
writeFileSync(out, `// Generated by tools/build-file-icons.mjs from PyCharm's New UI file type icons (IntelliJ Platform, Apache License 2.0)
// and tools/file-icons/. Do not edit.
window.PYIDE_FILE_ICONS = ${JSON.stringify({ light, dark }, null, 1)};
`);
console.log(`wrote ${Object.keys(light).length} icons (${Object.keys(dark).length} with dark variants) to ${out}`);
