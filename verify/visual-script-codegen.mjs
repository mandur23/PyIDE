// ---------- precedence: random expression trees keep their shape with the fewest parentheses ----------
{
  let seed = 7;
  const rand = () => {
    seed = (seed * 1103515245 + 12345) % 2147483648;
    return seed / 2147483648;
  };
  const pick = (list) => list[Math.floor(rand() * list.length)];
  const nodes = { n1: ['core.start'] };
  const wires = [];
  let id = 1;
  const add = (type, extra = {}) => {
    const nid = `n${++id}`;
    nodes[nid] = [type, extra];
    return nid;
  };
  // Builds a subtree into `target` (a node id and input pin) and returns its fully parenthesized Python text.
  const build = (kind, depth, target) => {
    const literal = depth <= 0 || rand() < 0.25;
    if (kind === 'number' && literal) {
      const v = pick([0, 1, 2, 3, 7, -2, -1, 2.5, -0.5]);
      if (rand() < 0.5) nodes[target[0]][1].inputs = { ...(nodes[target[0]][1].inputs || {}), [target[1]]: v };
      else wires.push(`${add('value.number', { props: { value: v } })}.value -> ${target[0]}.${target[1]}`);
      return v < 0 ? `(${v})` : String(v);
    }
    if (kind === 'bool' && literal) {
      const v = rand() < 0.5;
      wires.push(`${add('value.bool', { props: { value: v } })}.value -> ${target[0]}.${target[1]}`);
      return v ? 'True' : 'False';
    }
    const two = (type, op, a, b) => {
      const n = add(type, op ? { props: { op } } : {});
      wires.push(`${n}.result -> ${target[0]}.${target[1]}`);
      return `(${build(a, depth - 1, [n, 'a'])} ${op || (type === 'math.and' ? 'and' : 'or')} ${build(b, depth - 1, [n, 'b'])})`;
    };
    const one = (type, word, a) => {
      const n = add(type);
      wires.push(`${n}.result -> ${target[0]}.${target[1]}`);
      return `(${word}${build(a, depth - 1, [n, 'value'])})`;
    };
    if (kind === 'number') {
      return rand() < 0.2 ? one('math.negate', '-', 'number') : two('math.binary', pick(['+', '-', '*', '/', '//', '%', '**']), 'number', 'number');
    }
    const r = rand();
    if (r < 0.5) return two('math.compare', pick(['==', '!=', '<', '<=', '>', '>=']), pick(['number', 'number', 'bool']), pick(['number', 'bool']));
    if (r < 0.8) return two(pick(['math.and', 'math.or']), null, 'bool', 'bool');
    return one('math.not', 'not ', 'bool');
  };
  const full = [];
  let prev = 'n1.next';
  for (let k = 0; k < 250; k++) {
    const p = add('io.print');
    wires.push(`${prev} -> ${p}.in`);
    prev = `${p}.next`;
    full.push(build(pick(['number', 'bool']), 1 + Math.floor(rand() * 4), [p, 'value']));
  }
  const r = VS.compile(graph(nodes, wires), { fileName: 'precedence.pyflow' });
  check(!VS.hasErrors(r), 'precedence: the expression graph compiles', JSON.stringify(r.errors.slice(0, 3)));
  const minimal = r.code.split('\n').filter((l) => l.startsWith('    print(')).map((l) => l.slice('    print('.length, -1));
  const pairs = minimal.map((m, i) => [m, full[i]]);
  const res = python(['-c', [
    'import ast, json, sys',
    // (a or b) or c and a or b or c parse differently but always give the same result, so BoolOps are flattened.
    'class Flat(ast.NodeTransformer):',
    '    def visit_BoolOp(self, node):',
    '        self.generic_visit(node)',
    '        values = []',
    '        for v in node.values:',
    '            values += v.values if isinstance(v, ast.BoolOp) and type(v.op) is type(node.op) else [v]',
    '        node.values = values',
    '        return node',
    'shape = lambda s: ast.dump(Flat().visit(ast.parse(s, mode="eval")))',
    'bad = [p for p in json.load(sys.stdin) if shape(p[0]) != shape(p[1])]',
    'print(json.dumps(bad[:5]))',
    'print(len(bad))',
  ].join('\n')], JSON.stringify(pairs));
  const extra = minimal.join('').split('(').length - 1;
  const fullCount = full.join('').split('(').length - 1;
  check(minimal.length === 250 && res.status === 0 && res.stdout.trim().endsWith('\n0'),
    `precedence: 250 generated expressions parse to the same tree as their fully parenthesized form (${extra} parentheses instead of ${fullCount})`, res.stdout + res.stderr);
}

