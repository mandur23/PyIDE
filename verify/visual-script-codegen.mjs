function problems(name, g, expected, { warningsOnly = false } = {}) {
  const r = VS.compile(g, { fileName: `${name}.pyflow` });
  for (const [node, text, extra = {}] of expected) {
    const hit = r.errors.find((e) => e.node === node && e.message.includes(text)
      && Object.entries(extra).every(([k, v]) => e[k] === v));
    check(!!hit, `${name}: reports ${JSON.stringify(text)} on ${node}`, JSON.stringify(r.errors));
  }
  check(VS.hasErrors(r) === !warningsOnly, `${name}: ${warningsOnly ? 'only warnings, Run may go ahead' : 'Run refuses'}`, JSON.stringify(r.errors));
  check(r.code.startsWith('# Generated by PyIDE') && r.code.includes('def main():'), `${name}: code is still produced`);
  written.push(writePy(r.code));
  return r;
}
