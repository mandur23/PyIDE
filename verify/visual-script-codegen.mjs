// ---------- runtime errors map back to the node ----------
function tracebackNode(name, g, expectedNode, expectedError) {
  const r = VS.compile(g, { fileName: `${name}.pyflow` });
  check(!VS.hasErrors(r), `${name}: compiles`, JSON.stringify(r.errors));
  const file = writePy(r.code);
  const res = python([file]);
  check(res.status !== 0 && res.stderr.includes(expectedError), `${name}: raises ${expectedError}`, res.stderr);
  const frames = [...res.stderr.matchAll(/File "([^"]+)", line (\d+)/g)].filter((m) => path.resolve(m[1]) === path.resolve(file));
  const line = frames.length ? Number(frames[frames.length - 1][2]) : 0;
  check(r.map[line] === expectedNode, `${name}: the traceback's last line in the generated file (${line}) maps to ${expectedNode}`, `got ${r.map[line]}\n${res.stderr}`);
}
