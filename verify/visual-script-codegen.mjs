// nodes: {id: [type, {props, inputs}]}; wires: 'n1.next -> n2.in'. Built through VS.parse, so the shape is checked too.
function graph(nodes, wires = []) {
  const list = Object.entries(nodes).map(([id, [type, extra = {}]], i) => ({ id, type, x: 100 + 240 * (i % 6), y: 100 + 160 * Math.floor(i / 6), ...extra }));
  const links = wires.map((w) => {
    const [a, b] = w.split(/\s*->\s*/).map((s) => s.trim().split('.'));
    return { from: { node: a[0], pin: a[1] }, to: { node: b[0], pin: b[1] } };
  });
  return VS.parse(JSON.stringify({ format: 1, nodes: list, links }));
}

let fileNo = 0;
const written = [];
function writePy(code) {
  const file = path.join(tmp, `g${++fileNo}.py`);
  writeFileSync(file, code, 'utf8');
  written.push(file);
  return file;
}
const lineOf = (code, text) => code.split('\n').findIndex((l) => l === text) + 1;
const usedTypes = new Set();

// Runs a graph that must compile cleanly and compares the real output.
function runs(name, g, expected, { stdin = '', lines = [] } = {}) {
  for (const n of g.nodes) usedTypes.add(n.type);
  const r = VS.compile(g, { fileName: `${name}.pyflow` });
  check(!VS.hasErrors(r) && !r.errors.length, `${name}: compiles without problems`, JSON.stringify(r.errors));
  check(VS.compile(VS.parse(VS.serialize(g)), { fileName: `${name}.pyflow` }).code === r.code, `${name}: the same graph read back from its file gives the same code`);
  check(r.map.length === r.code.split('\n').length, `${name}: map has one entry per line (index = line number)`, `${r.map.length} vs ${r.code.split('\n').length}`);
  for (const [text, node] of lines) {
    const at = lineOf(r.code, text);
    check(at > 0, `${name}: generates the line ${JSON.stringify(text)}`, r.code);
    if (at > 0 && node) check(r.map[at] === node, `${name}: line ${at} ${JSON.stringify(text)} maps to ${node}`, `got ${r.map[at]}`);
  }
  const res = python([writePy(r.code)], stdin);
  check(res.status === 0 && res.stdout.replace(/\r\n/g, '\n') === expected, `${name}: runs and prints the expected output`,
    `status ${res.status}\n--- stdout\n${res.stdout}\n--- expected\n${expected}\n--- stderr\n${res.stderr}\n--- code\n${r.code}`);
  return r;
}

